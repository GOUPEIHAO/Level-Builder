function shortUid(prefix: string): string {
  return `${prefix}_${Math.random().toString(36).slice(2, 7)}`;
}

/**
 * Creates a brand-new standalone LevelDocument from a RoomTemplateDefinition
 */
export function createSceneFromRoomTemplate(templateId: string): LevelDocument {
  const tpl = ROOM_TEMPLATES.find((t) => t.id === templateId) || ROOM_TEMPLATES[0];
  const built = tpl.build();
  const baseMetrics = structuredClone(METRICS_PRESETS[tpl.metricsPresetKey] || METRICS_PRESETS.tactical_tps);

  if (tpl.dimensionMode === '2d_side') {
    baseMetrics.cameraMode = 'side_2d';
    baseMetrics.cameraDistance = 14.0;
    baseMetrics.cameraPitch = 0;
  } else if (tpl.dimensionMode === '2d_topdown') {
    baseMetrics.cameraMode = 'topdown';
    baseMetrics.cameraDistance = 13.0;
    baseMetrics.cameraPitch = -55;
  }

  return {
    version: '1.3.0',
    metadata: {
      name: `${tpl.nameZh}`,
      author: 'LevelForge Template',
      genre: tpl.nameEn,
      dimensionMode: tpl.dimensionMode,
      gridSize: 0.5,
      snapRotation: 15,
      targetCompletionTimeSec: 45,
      description: `${tpl.summaryZh} — ${tpl.designTheoryZh}`,
      updatedAt: new Date().toISOString(),
    },
    metricsProfile: baseMetrics,
    sectionPlane: structuredClone(tpl.sectionPlane),
    blocks: built.blocks,
    pois: built.pois,
    paths: built.paths,
    jumps: built.jumps,
    sightlines: built.sightlines,
  };
}

/**
 * Appends/Stamps a Room Template into an existing LevelDocument with automatic non-overlapping offset
 */
export function appendRoomTemplateToDoc(
  doc: LevelDocument,
  templateId: string,
  customOffset?: Vec3
): { doc: LevelDocument; message: string; affectedIds: string[] } {
  const tpl = ROOM_TEMPLATES.find((t) => t.id === templateId);
  if (!tpl) {
    return { doc, message: `Template ${templateId} not found`, affectedIds: [] };
  }

  const next = structuredClone(doc);
  const built = tpl.build();
  const affectedIds: string[] = [];

  // Determine smart offset so appended room doesn't collide with existing blocks unless scene is empty
  let offset: Vec3 = customOffset || [0, 0, 0];
  if (!customOffset && next.blocks.length > 0) {
    let maxX = -Infinity;
    for (const b of next.blocks) {
      const right = b.position[0] + b.size[0] / 2;
      if (right > maxX) maxX = right;
    }
    offset = [Math.round((maxX + 16) * 2) / 2, 0, 0];
  }

  const idMap = new Map<string, string>();
  for (const b of built.blocks) {
    idMap.set(b.id, shortUid(b.id));
  }
  for (const p of built.pois) {
    idMap.set(p.id, shortUid(p.id));
  }

  for (const b of built.blocks) {
    const newId = idMap.get(b.id)!;
    next.blocks.push({
      ...b,
      id: newId,
      position: [
        Number((b.position[0] + offset[0]).toFixed(2)),
        Number((b.position[1] + offset[1]).toFixed(2)),
        Number((b.position[2] + offset[2]).toFixed(2)),
      ],
      linkedId: b.linkedId ? idMap.get(b.linkedId) || b.linkedId : undefined,
    });
    affectedIds.push(newId);
  }

  for (const p of built.pois) {
    // If appending to a scene that already has a player spawn, convert extra spawn_player to checkpoint
    const hasPlayerSpawn = next.pois.some((x) => x.category === 'spawn_player');
    const newId = idMap.get(p.id)!;
    next.pois.push({
      ...p,
      id: newId,
      category: p.category === 'spawn_player' && hasPlayerSpawn ? 'checkpoint' : p.category,
      name: p.category === 'spawn_player' && hasPlayerSpawn ? `${p.name} (检查点)` : p.name,
      position: [
        Number((p.position[0] + offset[0]).toFixed(2)),
        Number((p.position[1] + offset[1]).toFixed(2)),
        Number((p.position[2] + offset[2]).toFixed(2)),
      ],
      linkedId: p.linkedId ? idMap.get(p.linkedId) || p.linkedId : undefined,
      enemyConfig: p.enemyConfig
        ? {
            ...p.enemyConfig,
            waypoints: p.enemyConfig.waypoints.map((wp) => [
              Number((wp[0] + offset[0]).toFixed(2)),
              Number((wp[1] + offset[1]).toFixed(2)),
              Number((wp[2] + offset[2]).toFixed(2)),
            ]),
          }
        : undefined,
    });
    affectedIds.push(newId);
  }

  for (const path of built.paths) {
    const pid = shortUid('path');
    next.paths.push({
      ...path,
      id: pid,
      points: path.points.map((pt) => [
        Number((pt[0] + offset[0]).toFixed(2)),
        Number((pt[1] + offset[1]).toFixed(2)),
        Number((pt[2] + offset[2]).toFixed(2)),
      ]),
    });
  }

  for (const j of built.jumps) {
    const jid = shortUid('jmp');
    next.jumps.push({
      ...j,
      id: jid,
      from: [j.from[0] + offset[0], j.from[1] + offset[1], j.from[2] + offset[2]],
      to: [j.to[0] + offset[0], j.to[1] + offset[1], j.to[2] + offset[2]],
    });
  }

  return {
    doc: next,
    message: `已生成房间模块「${tpl.nameZh}」(偏移 X:${offset[0]}m, 共新增 ${affectedIds.length} 个组件)`,
    affectedIds,
  };
}
