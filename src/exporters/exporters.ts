import * as THREE from 'three';
import { GLTFExporter } from 'three/examples/jsm/exporters/GLTFExporter.js';
import { auditLevel, computeCrossSection, getBlockTrianglesWorld, POI_META, ROLE_META } from '../core/geometry-analysis';
import { LevelDocument } from '../core/types';

function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function exportLevelJSON(doc: LevelDocument): void {
  const json = JSON.stringify(doc, null, 2);
  const blob = new Blob([json], { type: 'application/json' });
  const safeName = doc.metadata.name.replace(/[^\w\u4e00-\u9fa5-]+/g, '_');
  triggerDownload(blob, `${safeName}.level.json`);
}

export function exportLevelOBJ(doc: LevelDocument): void {
  const lines: string[] = [
    `# LevelForge Greybox Export (Wavefront OBJ)`,
    `# Level: ${doc.metadata.name}`,
    `# Units: Meters (1 unit = 1m)`,
    ``,
  ];
  let vertexOffset = 1;

  for (const b of doc.blocks) {
    if (b.hidden) continue;
    const safeObjName = `${b.id}_${b.role}`.replace(/\s+/g, '_');
    lines.push(`o ${safeObjName}`);
    lines.push(`g ${b.role}`);
    const tris = getBlockTrianglesWorld(b);
    for (const t of tris) {
      lines.push(`v ${t.a[0].toFixed(4)} ${t.a[1].toFixed(4)} ${t.a[2].toFixed(4)}`);
      lines.push(`v ${t.b[0].toFixed(4)} ${t.b[1].toFixed(4)} ${t.b[2].toFixed(4)}`);
      lines.push(`v ${t.c[0].toFixed(4)} ${t.c[1].toFixed(4)} ${t.c[2].toFixed(4)}`);
      lines.push(`f ${vertexOffset} ${vertexOffset + 1} ${vertexOffset + 2}`);
      vertexOffset += 3;
    }
    lines.push(``);
  }

  const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' });
  const safeName = doc.metadata.name.replace(/[^\w\u4e00-\u9fa5-]+/g, '_');
  triggerDownload(blob, `${safeName}_blockout.obj`);
}

export function exportLevelGLB(sceneGroup: THREE.Object3D, doc: LevelDocument): void {
  const exporter = new GLTFExporter();
  const safeName = doc.metadata.name.replace(/[^\w\u4e00-\u9fa5-]+/g, '_');
  exporter.parse(
    sceneGroup,
    (result) => {
      if (result instanceof ArrayBuffer) {
        triggerDownload(new Blob([result], { type: 'model/gltf-binary' }), `${safeName}.glb`);
      } else {
        const json = JSON.stringify(result, null, 2);
        triggerDownload(new Blob([json], { type: 'model/gltf+json' }), `${safeName}.gltf`);
      }
    },
    (err) => {
      console.error('GLTF export failed:', err);
    },
    { binary: true }
  );
}

export function exportUnityCS(doc: LevelDocument): void {
  const lines: string[] = [
    `// Auto-generated by LevelForge for Unity Editor`,
    `// Place this file inside Assets/Editor/LevelForgeBuilder.cs and run menu: Tools -> LevelForge -> Build Greybox Level`,
    `#if UNITY_EDITOR`,
    `using UnityEngine;`,
    `using UnityEditor;`,
    ``,
    `public static class LevelForgeBuilder`,
    `{`,
    `    [MenuItem("Tools/LevelForge/Build Greybox Level")]`,
    `    public static void BuildLevel()`,
    `    {`,
    `        GameObject root = new GameObject(${JSON.stringify(doc.metadata.name)});`,
    `        Undo.RegisterCreatedObjectUndo(root, "Build LevelForge Greybox");`,
  ];

  for (const b of doc.blocks) {
    if (b.hidden) continue;
    // Note: In Three.js -Z is North; in Unity +Z is North, so flip Z coordinate
    const ux = b.position[0];
    const uy = b.position[1];
    const uz = -b.position[2];
    const prim = b.type === 'cylinder' ? 'PrimitiveType.Cylinder' : 'PrimitiveType.Cube';
    const scaleY = b.type === 'cylinder' ? b.size[1] / 2 : b.size[1];
    lines.push(`        {`);
    lines.push(`            GameObject go = GameObject.CreatePrimitive(${prim});`);
    lines.push(`            go.name = ${JSON.stringify(`${b.name} [${b.role}]`)};`);
    lines.push(`            go.transform.SetParent(root.transform);`);
    lines.push(`            go.transform.position = new Vector3(${ux}f, ${uy}f, ${uz}f);`);
    lines.push(`            go.transform.eulerAngles = new Vector3(${b.rotation[0]}f, ${-b.rotation[1]}f, ${b.rotation[2]}f);`);
    lines.push(`            go.transform.localScale = new Vector3(${b.size[0]}f, ${scaleY}f, ${b.size[2]}f);`);
    lines.push(`        }`);
  }

  for (const p of doc.pois) {
    lines.push(`        {`);
    lines.push(`            GameObject poi = new GameObject(${JSON.stringify(`POI_${p.category}_${p.name}`)});`);
    lines.push(`            poi.transform.SetParent(root.transform);`);
    lines.push(`            poi.transform.position = new Vector3(${p.position[0]}f, ${p.position[1]}f, ${-p.position[2]}f);`);
    lines.push(`            poi.transform.eulerAngles = new Vector3(0f, ${p.yaw}f, 0f);`);
    lines.push(`        }`);
  }

  lines.push(`        Selection.activeGameObject = root;`);
  lines.push(`        Debug.Log("[LevelForge] Greybox level built successfully!");`);
  lines.push(`    }`);
  lines.push(`}`);
  lines.push(`#endif`);

  const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' });
  triggerDownload(blob, `LevelForgeBuilder.cs`);
}

export function exportBlueprintSVG(doc: LevelDocument): void {
  const { sectionLength, items } = computeCrossSection(doc);
  const scale = 14;
  const svgW = 1000;
  const svgH = 760;
  const topCenterX = 500;
  const topCenterY = 230;
  const secOriginX = 500 - (sectionLength * scale) / 2;
  const secBaseY = 640;

  const parts: string[] = [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${svgW} ${svgH}" width="${svgW}" height="${svgH}" style="background:#0b111e;font-family:Inter,system-ui,sans-serif;">`,
    `<rect width="100%" height="100%" fill="#0b111e"/>`,
    `<text x="28" y="34" fill="#f8fafc" font-size="16" font-weight="bold">LevelForge 关卡设计蓝图 — ${doc.metadata.name}</text>`,
    `<text x="28" y="54" fill="#94a3b8" font-size="11">1. 2D 俯视平面图 (Top-Down Plan View) | 比例 1m = ${scale}px</text>`,
    `<line x1="20" y1="440" x2="${svgW - 20}" y2="440" stroke="#334155" stroke-width="1.5"/>`,
    `<text x="28" y="468" fill="#94a3b8" font-size="11">2. A-A' 实时剖面图 (Cross-Section View, 切线总长 ${sectionLength.toFixed(1)}m)</text>`,
  ];

  // Top-Down Blocks
  const sortedBlocks = doc.blocks
    .filter((b) => !b.hidden)
    .slice()
    .sort((a, b) => a.position[1] - b.position[1]);

  for (const b of sortedBlocks) {
    const col = b.color || ROLE_META[b.role]?.color || '#64748b';
    const x = topCenterX + (b.position[0] - b.size[0] / 2) * scale;
    const y = topCenterY + (b.position[2] - b.size[2] / 2) * scale;
    const w = b.size[0] * scale;
    const h = b.size[2] * scale;
    const cx = topCenterX + b.position[0] * scale;
    const cy = topCenterY + b.position[2] * scale;
    parts.push(
      `<g transform="rotate(${-b.rotation[1]} ${cx} ${cy})">`,
      `<rect x="${x.toFixed(1)}" y="${y.toFixed(1)}" width="${w.toFixed(1)}" height="${h.toFixed(1)}" fill="${col}" fill-opacity="0.75" stroke="#e2e8f0" stroke-width="1"/>`,
      w > 35 && h > 16
        ? `<text x="${cx.toFixed(1)}" y="${(cy + 3).toFixed(1)}" fill="#f8fafc" font-size="9" text-anchor="middle">${b.name}</text>`
        : '',
      `</g>`
    );
  }

  // Section line A-A' on Top-Down
  const sx0 = topCenterX + doc.sectionPlane.start[0] * scale;
  const sy0 = topCenterY + doc.sectionPlane.start[1] * scale;
  const sx1 = topCenterX + doc.sectionPlane.end[0] * scale;
  const sy1 = topCenterY + doc.sectionPlane.end[1] * scale;
  parts.push(
    `<line x1="${sx0}" y1="${sy0}" x2="${sx1}" y2="${sy1}" stroke="#f43f5e" stroke-width="2" stroke-dasharray="8 4"/>`,
    `<circle cx="${sx0}" cy="${sy0}" r="6" fill="#f43f5e"/><text x="${sx0}" y="${sy0 - 9}" fill="#fb7185" font-size="10" font-weight="bold" text-anchor="middle">A</text>`,
    `<circle cx="${sx1}" cy="${sy1}" r="6" fill="#f43f5e"/><text x="${sx1}" y="${sy1 - 9}" fill="#fb7185" font-size="10" font-weight="bold" text-anchor="middle">A'</text>`
  );

  // Cross-Section Datum line (0.0m)
  parts.push(
    `<line x1="60" y1="${secBaseY}" x2="${svgW - 60}" y2="${secBaseY}" stroke="#38bdf8" stroke-width="1.2" stroke-dasharray="4 4"/>`,
    `<text x="65" y="${secBaseY - 5}" fill="#38bdf8" font-size="10">±0.0m 基准地面</text>`
  );

  // Cross-Section Cut Polygons
  for (const item of items) {
    const col = item.block.color || ROLE_META[item.block.role]?.color || '#64748b';
    for (const poly of item.cutPolygons) {
      if (poly.length < 3) continue;
      const ptsStr = poly
        .map(([u, v]) => `${(secOriginX + u * scale).toFixed(1)},${(secBaseY - v * scale).toFixed(1)}`)
        .join(' ');
      parts.push(`<polygon points="${ptsStr}" fill="${col}" fill-opacity="0.7" stroke="#f8fafc" stroke-width="1.5"/>`);
    }
  }

  parts.push(`</svg>`);
  const blob = new Blob([parts.join('\n')], { type: 'image/svg+xml;charset=utf-8' });
  const safeName = doc.metadata.name.replace(/[^\w\u4e00-\u9fa5-]+/g, '_');
  triggerDownload(blob, `${safeName}_blueprint.svg`);
}

export function exportDesignDocMarkdown(doc: LevelDocument): void {
  const audit = auditLevel(doc);
  const m = doc.metricsProfile;
  const dimLabel =
    doc.metadata.dimensionMode === '2d_side'
      ? '2D 横版卷轴 (2D Side-Scroller)'
      : doc.metadata.dimensionMode === '2d_topdown'
      ? '2D 俯视角地牢 (2D Top-Down)'
      : '3D 立体空间 (3D Spatial)';

  const lines: string[] = [
    `# 📐 关卡设计文档 (LDD) — ${doc.metadata.name}`,
    ``,
    `- **游戏品类 / 维度模式**: ${doc.metadata.genre} (${dimLabel})`,
    `- **设计概述**: ${doc.metadata.description}`,
    `- **更新时间**: ${doc.metadata.updatedAt}`,
    ``,
    `## 1. 角色度量衡与摄像机参数 (Metrics & Camera Profile)`,
    `| 参数项 | 数值 | 说明 |`,
    `| :--- | :--- | :--- |`,
    `| 角色身高 / 下蹲高 | ${m.playerHeight}m / ${m.crouchHeight}m | 胶囊半径 ${m.playerRadius}m，眼高 ${m.eyeHeight}m |`,
    `| 移动速度 (走/跑/蹲) | ${m.walkSpeed} / ${m.runSpeed} / ${m.crouchSpeed} m/s | 最大爬坡角 ${m.maxSlopeAngle}° |`,
    `| 跳跃包络 (单跳/二段跳) | 高 ${m.jumpHeight}m (远 ${m.jumpDistance}m) / 二段高 ${m.doubleJumpHeight}m (远 ${m.doubleJumpDistance}m) | 重力 ${m.gravity} m/s² |`,
    `| 掩体高度标准 | 半身 ${m.lowCoverHeight}m / 全身 ${m.fullCoverHeight}m | 最小走廊宽 ${m.minCorridorWidth}m |`,
    `| 玩家摄像机配置 | ${(m.cameraMode ?? 'tps').toUpperCase()} · FOV ${m.cameraFov ?? 68}° | 弹簧臂长 ${m.cameraDistance ?? 3.2}m · 俯仰角 ${m.cameraPitch ?? -10}° |`,
    ``,
    `## 2. 空间指标与心流节奏评估 (Spatial & Pacing Summary)`,
    `- **可行走总面积**: ${audit.totalWalkableArea} ㎡`,
    `- **掩体总长 / 掩体密度比**: ${audit.totalCoverLength}m (${audit.coverToAreaRatio}%)`,
    `- **主线动线总长与预计耗时**: ${audit.mainPathDistance}m (奔跑 ${audit.estimatedRunTimeSec}s / 步行 ${audit.estimatedWalkTimeSec}s)`,
    `- **高程跨度**: ${audit.elevationSpan[0]}m ~ +${audit.elevationSpan[1]}m`,
    `- **心流节奏诊断**: ${audit.pacingVerdict || '正常'}`,
    ``,
    `## 3. 关卡白盒构件与设计思路清单 (Blockout Design Notes)`,
    `| ID | 构件名称 | 语义角色 | 尺寸 (W×H×D) | 坐标 (X,Y,Z) | 设计定位标签 | 核心设计思路与机制说明 |`,
    `| :--- | :--- | :--- | :--- | :--- | :--- | :--- |`,
  ];

  for (const b of doc.blocks) {
    const roleLbl = ROLE_META[b.role]?.label.split(' ')[0] || b.role;
    const tag = b.designTag || '-';
    const note = [b.notes, b.mechanicsTip ? `[机制: ${b.mechanicsTip}]` : ''].filter(Boolean).join(' ') || '-';
    lines.push(
      `| \`${b.id}\` | **${b.name}** | ${roleLbl} | ${b.size.join('×')}m | (${b.position.join(', ')}) | ${tag} | ${note} |`
    );
  }

  lines.push(
    ``,
    `## 4. 关键兴趣点、敌人巡逻与机关拓扑 (POIs & AI Encounters)`,
    `| ID | 名称 | 类别 | 坐标 (X,Y,Z) | 设计定位标签 | 核心设计思路 / 巡逻与联动配置 |`,
    `| :--- | :--- | :--- | :--- | :--- | :--- |`
  );

  for (const p of doc.pois) {
    const catLbl = POI_META[p.category]?.label.split(' ')[0] || p.category;
    const tag = p.designTag || '-';
    const patrolInfo = p.enemyConfig?.waypoints?.length
      ? `[巡逻: ${p.enemyConfig.patrolMode}, ${p.enemyConfig.waypoints.length}点位, 移速${p.enemyConfig.patrolSpeed}m/s]`
      : '';
    const linkInfo = p.linkedId ? `[联动目标: ${p.linkedId}]` : '';
    const note = [p.notes, p.mechanicsTip, patrolInfo, linkInfo].filter(Boolean).join(' ') || '-';
    lines.push(`| \`${p.id}\` | **${p.name}** | ${catLbl} | (${p.position.join(', ')}) | ${tag} | ${note} |`);
  }

  const blob = new Blob([lines.join('\n')], { type: 'text/markdown;charset=utf-8' });
  const safeName = doc.metadata.name.replace(/[^\w\u4e00-\u9fa5-]+/g, '_');
  triggerDownload(blob, `${safeName}_LevelDesignDoc.md`);
}
